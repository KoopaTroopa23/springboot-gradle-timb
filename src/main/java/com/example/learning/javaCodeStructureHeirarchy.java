package com.example.learning;

// import statements go here — they bring in other Java classes or libraries
// For example: import java.util.Scanner;

public class javaCodeStructureHeirarchy {

    public static void main(String[] args) {

        System.out.println("Java Code Structure - Beginner Guide\n");

        System.out.println("1. Package");
        System.out.println("   - Groups related classes into folders (e.g., com.example.learning).\n");

        System.out.println("2. Import");
        System.out.println("   - Brings in built-in or external classes (e.g., import java.util.Scanner;).\n");

        System.out.println("3. Class");
        System.out.println("   - A blueprint for creating objects (e.g., public class Dog {}).\n");

        System.out.println("4. Object");
        System.out.println("   - A real instance created from a class (e.g., Dog myDog = new Dog();).\n");

        System.out.println("5. Method");
        System.out.println("   - A block inside a class that performs an action (e.g., main method).\n");

        System.out.println("6. Statement");
        System.out.println("   - A single line of code that performs a task (e.g., System.out.println()).\n");

        System.out.println("7. Expression");
        System.out.println("   - A piece of code that evaluates to a value (e.g., 5 + 3).\n");

        System.out.println("8. Variable");
        System.out.println("   - A container that holds data (e.g., int score = 10;).\n");
    }
}
